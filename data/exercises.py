CATALOG: dict[str, Exercise] = {key: Exercise(key, name, group, image, tip) for key, name, group, image, tip in _RAW}

_BY_NAME: dict[str, Exercise] = {ex.name.lower(): ex for ex in CATALOG.values()}

MAX_ALTERNATIVES = 10


def alternatives_for(key: str | None) -> list[Exercise]:
    """Упражнения той же группы мышц, кроме текущего."""
    current = CATALOG.get(key) if key else None
    if current is None:
        return []
    return [ex for ex in CATALOG.values() if ex.group == current.group and ex.key != key][:MAX_ALTERNATIVES]


def in_group(group: str) -> list[Exercise]:
    return [ex for ex in CATALOG.values() if ex.group == group]


def muscle_of(group: str) -> Muscle | None:
    return _MUSCLE_OF_GROUP.get(group)


def muscle_label(key: str | None) -> str | None:
    """«Ноги · Икры» — для карточки упражнения."""
    item = CATALOG.get(key or "")
    if item is None:
        return None
    part, muscle = _PART_OF_GROUP.get(item.group), _MUSCLE_OF_GROUP.get(item.group)
    if part is None or muscle is None:
        return MUSCLE_GROUPS.get(item.group)
    part_title = BODY_PARTS[part][0].split(" ", 1)[1]
    return f"{part_title} · {muscle.title}"


def in_muscle(muscle_key: str) -> list[Exercise]:
    muscle = MUSCLES.get(muscle_key)
    return [ex for g in muscle.groups for ex in in_group(g)] if muscle else []


def find_by_name(name: str) -> Exercise | None:
    """Точное совпадение с названием из каталога — чтобы у введённого вручную упражнения была картинка."""
    return _BY_NAME.get(name.strip().lower())
